"""REPORT.md from the files in outputs/. Every number in the report comes from those files.

Usage: python scripts/build_report.py --out outputs --report REPORT.md
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
PRIMARY_H = 5


def pct(x: float, digits: int = 2) -> str:
    return "n/a" if pd.isna(x) else f"{100 * x:.{digits}f}%"


def table(df: pd.DataFrame) -> str:
    head = "| " + " | ".join(df.columns) + " |\n| " + " | ".join("---" for _ in df.columns) + " |\n"
    return head + "\n".join("| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False))


def horizon_label(m: int) -> str:
    return "none" if m == 0 else (f"{m // 60} h" if m >= 60 and m % 60 == 0 else f"{m} min")


def build(out: Path) -> str:
    params = pd.read_csv(out / "params.csv")
    cov = pd.read_csv(out / "coverage.csv")
    prim = pd.read_csv(out / "primary.csv")
    hor = pd.read_csv(out / "horizons.csv")
    oct10 = pd.read_csv(out / "oct10.csv")
    proxy = pd.read_csv(out / "proxy.csv")
    hlp = json.loads((out / "hlp_summary.json").read_text())
    manifest = pd.read_csv(out / "manifest.csv")
    recount = pd.read_csv(out / "recompute.csv") if (out / "recompute.csv").exists() else None

    inc = params[params.status == "included"].copy()
    lev = inc.set_index("asset").max_leverage
    n_assets, n_sides = len(inc), len(prim)
    counts = prim.classification.value_counts()
    hor["max_leverage"] = hor.asset.map(lev)
    corr_median = proxy.return_correlation.median()
    proxy_ok = corr_median >= 0.95

    lines = [
        "# How long do Hyperliquid's maintenance margins hold?",
        "",
        "Generated by `scripts/build_report.py` from `outputs/`. Method: `PROTOCOL.md`.",
        "",
        "## 1. Summary",
        "",
        (f"- Universe: {n_assets} perpetuals with a Binance price history that passes the data gates; "
        f"{(params.status != 'included').sum()} assets excluded (section 2)."),
        (f"- Primary test, adverse move at the end of 5-minute windows against the maintenance margin rate: "
        f"{counts.get('below 99%', 0)} of {n_sides} asset-sides cover less than 99% of windows, "
        f"{counts.get('at or above 99%', 0)} cover at least 99%, {counts.get('not distinguishable', 0)} cannot be "
        "told apart from 99% (Holm, 5% family-wise)."),
        (f"- Horizon of coverage: the median asset covers 99% of moves up to {horizon_label(int(hor.h_star_min.quantile(0.5, interpolation='lower')))} "
        f"({horizon_label(int(hor.h_star_conf_min.quantile(0.5, interpolation='lower')))} with the bootstrap bound). "
        f"European central counterparties must cover two business days for exchange-traded derivatives "
        "(Commission Delegated Regulation (EU) No 153/2013, article 26)."),
    ]
    b5 = oct10[(oct10.horizon_min == 5)].groupby("asset")[["breach_B1"]].any()
    b5m1 = oct10[(oct10.horizon_min == 5) & (oct10.measure == "M1")].groupby("asset").breach_B1.any()
    lines.append(
        f"- 10 October 2025, 20:00 to 22:00 UTC: {int(b5m1.sum())} of {len(b5m1)} assets moved beyond their "
        f"maintenance margin at the end of some 5-minute window, {int(b5.breach_B1.sum())} at some point inside one.")
    lines.append(
        f"- Proxy: median correlation of 4-hour returns between Hyperliquid and Binance {corr_median:.3f} over "
        f"{len(proxy)} assets; " + ("the proxy passes the protocol's gate." if proxy_ok else
                                   "below the protocol's 0.95 gate: every result is Binance-based only."))
    lines += ["", "## 2. Data", ""]
    excl = params[params.status != "included"].status.value_counts()
    lines += [f"- Assets in the `meta` snapshot: {len(params)}; included: {n_assets}."]
    lines += [f"- Excluded ({k.removeprefix('excluded: ')}): {v}." for k, v in excl.items()]
    st = manifest.status.value_counts()
    lines += [f"- Asset-months: {len(manifest)}; " + ", ".join(f"{k}: {v}" for k, v in st.items()) + "."]

    lines += ["", "## 3. Coverage by horizon", "",
              "Share of asset-sides whose achieved coverage is at least 99%, and median coverage.", ""]
    rows = []
    for h, g in cov.groupby("horizon_min"):
        r = {"Horizon": horizon_label(int(h))}
        for (m, b), gg in g.groupby(["measure", "buffer"]):
            r[f"{m} {b} share >= 99%"] = pct((gg.coverage >= 0.99).mean(), 1)
            r[f"{m} {b} median"] = pct(gg.coverage.median(), 3)
        rows.append(r)
    lines += [table(pd.DataFrame(rows)), ""]

    lines += ["## 4. Primary cell by asset", "",
              "M1, maintenance margin rate, 5-minute windows. Interval: 95% stationary bootstrap of days.", ""]
    p = prim.merge(inc[["asset", "max_leverage", "mmr"]], on="asset").sort_values("exception_rate", ascending=False)
    p_tab = pd.DataFrame({
        "Asset": p.asset, "Side": p.side, "Max leverage": p.max_leverage.astype(int), "Margin": p.mmr.map(pct),
        "Exceptions": p.exceptions, "Windows": p.observations, "Coverage": (1 - p.exception_rate).map(lambda x: pct(x, 3)),
        "Rate 95% interval": [f"{pct(a, 3)} to {pct(b, 3)}" for a, b in zip(p.rate_lo, p.rate_hi)],
        "Classification": p.classification})
    lines += [table(p_tab), ""]

    lines += ["## 5. Horizon of coverage by maximum leverage", ""]

    def lower(s: pd.Series) -> float:
        """Lower median: a horizon of the grid, never the average of two."""
        return s.quantile(0.5, interpolation="lower")

    g = hor.groupby("max_leverage").agg(assets=("asset", "size"), median=("h_star_min", lower),
                                        median_conf=("h_star_conf_min", lower)).reset_index()
    lines += [table(pd.DataFrame({"Max leverage": g.max_leverage.astype(int), "Assets": g.assets,
                                  "Median h*": g["median"].map(lambda m: horizon_label(int(m))),
                                  "Median h* (bound)": g.median_conf.map(lambda m: horizon_label(int(m)))})), ""]

    lines += ["## 6. 10 October 2025", ""]
    o = oct10.merge(inc[["asset", "max_leverage"]], on="asset")
    rows = []
    for (h, m), gg in o.groupby(["horizon_min", "measure"]):
        by_asset = gg.groupby("asset")[["breach_B1", "breach_B2"]].any()
        rows.append({"Window": f"{int(h)} min", "Measure": m, "Assets": len(by_asset),
                     "Beyond maintenance margin": int(by_asset.breach_B1.sum()),
                     "Beyond 2/3 of it": int(by_asset.breach_B2.sum())})
    lines += [table(pd.DataFrame(rows)), ""]

    lines += ["## 7. Standard tests", "",
              ("Share of cells where the test rejects at 5%. These tests assume independent exceptions and decide "
              "nothing (protocol 6)."), ""]
    rows = []
    for (m, b), gg in cov.groupby(["measure", "buffer"]):
        rows.append({"Measure": m, "Buffer": b, "Cells": len(gg),
                     "Kupiec": pct((gg.kupiec_p < 0.05).mean(), 1),
                     "Christoffersen independence": pct((gg.christoffersen_ind_p < 0.05).mean(), 1),
                     "Conditional coverage": pct((gg.christoffersen_cc_p < 0.05).mean(), 1)})
    lines += [table(pd.DataFrame(rows)), ""]

    lines += ["## 8. Proxy check", ""]
    pr = proxy.dropna(subset=["return_correlation"])
    lines += [table(pd.DataFrame({
        "Asset": pr.asset, "4-hour windows": pr.windows, "From": pr["first"],
        "Return correlation": pr.return_correlation.map(lambda x: f"{x:.3f}"),
        "Range ratio": pr.median_range_ratio.map(lambda x: f"{x:.3f}"),
        "Disagreement": pr.m2_disagreement_share.map(lambda x: pct(x, 2)),
        "10/10 low, Hyperliquid": pr.oct10_hl_long_m2.map(pct),
        "10/10 low, Binance": pr.oct10_binance_long_m2.map(pct)})), ""]

    lines += ["## 9. HLP", ""]
    lines += [(f"- History: {hlp['points']} points from {hlp['first'][:10]} to {hlp['last'][:10]}, median spacing "
              f"{hlp['median_spacing_days']:.2f} days."),
              (f"- Annualised return {pct(hlp['annual_return'])}, annualised volatility {pct(hlp['annual_volatility'])}, "
              f"maximum drawdown {pct(hlp['max_drawdown'])}.")]
    if hlp.get("oct10_period"):
        lines.append(f"- Period containing 10 October 2025 (ending {hlp['oct10_period']['end'][:16]}): "
                     f"{pct(hlp['oct10_period']['return'])}.")
    lines.append("- Worst periods: " + "; ".join(f"{w['end'][:10]} {pct(w['return'])}" for w in hlp["worst_periods"]) + ".")
    if "spearman_rho" in hlp:
        verdict = ("rejects the null: HLP did worse in periods with more margin breaches" if hlp["negative_link_rejects_null"]
                   else "does not reject the null that HLP's returns are not lower in periods with more breaches")
        lines.append(f"- Spearman correlation between HLP returns and primary-cell exceptions: {hlp['spearman_rho']:.3f} "
                     f"over {hlp['test_periods']} periods (bootstrap 95% upper bound {hlp['spearman_q95']:.3f}); the test {verdict}.")
    else:
        lines.append(f"- {hlp['test']}.")

    lines += ["", "## 10. Independent recount", ""]
    if recount is None:
        lines.append("- Not available.")
    else:
        lines.append(f"- {len(recount)} cells recounted for {recount.asset.nunique()} assets; "
                     f"{int((~recount.match).sum())} mismatches.")
    lines += ["", "## 11. Limitations", "", "See `PROTOCOL.md`, section 11.", ""]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT / "outputs")
    ap.add_argument("--report", type=Path, default=ROOT / "REPORT.md")
    args = ap.parse_args()
    args.report.write_text(build(args.out))


if __name__ == "__main__":
    np.seterr(all="ignore")
    main()
